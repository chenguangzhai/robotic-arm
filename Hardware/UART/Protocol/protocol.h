/**
  * 串口指令协议层：把 UART 字节流切成「一行一条命令」，解析后交给 Motion 执行
  *
  * 分层关系（三层互不知道对方内部）：
  *   uart_app.c   只负责搬字节（环形缓冲 + DMA，不知道什么叫命令）
  *   protocol.c   只负责切行 + 解析 + 分发（不知道 DMA 怎么工作，也不驱动舵机）
  *   motion.c     只负责「从当前点沿直线走到目标点」（不知道命令从哪来）
  *   main.c       主循环，按键和串口在这里汇合成同一份目标
  *
  * 为什么按 '\n' 切行，而不是按 DMA 的 IDLE 标志切帧：
  *   IDLE 只代表「总线静默了」，不代表「一条命令结束了」。连发
  *   "M 0.3 0.1 0\r\nM 0.2 0.1 0\r\n" 时两条命令很可能落在同一帧里，
  *   按帧切会把它们当成一条而解析失败。行缓冲天然处理跨帧的半条命令，
  *   所以这里完全不依赖 IDLE 语义。
  *
  * 指令集（大小写均可，参数之间空格/逗号都行，结尾 \n 或 \r\n）：
  *
 *   M x y z     移动到 (x,y,z)，单位【米】。例：M 0.28 0.10 0
 *               受理后立即回 OK，随后末端以当前巡航速度沿直线走过去，
 *               到位时主动推一行 DONE。注意 OK 的含义是「已受理」，
 *               不是「已到位」——要看 DONE。
 *   Y <角度>    纯偏航：只转底座，肩/肘/腕保持不动。单位【度】，允许 ±88。
 *               例：Y 15（向右偏 15°）、Y 0（回正前方）、Y -45（向左 45°）。
 *               进入本模式时锁定当前的半径 r 与高度 h，之后连续发 Y 只改朝向；
 *               发任何一条 M 就退回笛卡尔模式，起点是当前所在的弧上点。
 *
 *               为什么需要它（而不是把 M 的 z 改成角度）：
 *               M 的 z 改变时末端沿【直线】横移，到基座的距离 hypot(x,z)
 *               随之变大，肩/肘/腕必须跟着补偿 —— 现象就是「只想转个方向，
 *               结果四个关节一起动」。这是笛卡尔坐标的几何必然，不是 bug。
 *               而「把手臂转到另一个朝向」在柱坐标下就是纯偏航：r、h 恒定，
 *               只有底座动，俯仰三关节的逆解输入根本没变。
 *
 *               也不该把 M 的 z 直接改成角度：那样 x/y 是米、z 是度，
 *               Motion 里所有距离、速度、路径采样的式子都变成量纲混合，
 *               梯形剖面算出来的就不再是速度了。所以分成两条命令。
 *   G 0|1       夹爪开合：0 = 张开（0°），1 = 收紧（默认 60°，见 protocol.c
  *               的 GRIP_ANGLE_CLOSE，需按实际工件微调）。
  *               只驱动 PA7（舵机 6）。PA6（舵机 5）是旋转爪子，
  *               固定在中位 90°，暂无指令控制。
  *               立即到位、不走插值（插值要 3 秒，夹爪等不起）。
  *               回 OK 表示已下发，不是「夹到位」——夹爪没有位置反馈。
 *   R <角度>    夹爪旋转（PA6 / 舵机 5），0~180 度。
 *               0°  = 夹爪平行于地面（上电初始姿态）
 *               90° = 夹爪垂直于地面
 *               例：R 90（转垂直）、R 45（斜 45°）、R 0（回平行）
 *               立即到位；超范围回 ERR:RANGE。
 *
 * ---- 3.0 新增：速度在线可调 ----
 *
 *   V <mm/s>    设置末端巡航速度，允许 20~150（毫米/秒），回 "OK <mm/s>"。
 *               只改上限，不改「当前正在走的那一段」的安全边界：
 *               剩余距离不够时会自动减速，所以随时改都安全。
 *               'S <mm/s>' 是同一功能的别名（见下方说明）。
 *
 *               为什么做成指令而不是宏：motion.h 里原来写
 *               「MOTION_SPEED = 0.05，照 1mm/圈 × 20Hz 估的，未实测」。
 *               未实测的参数如果只能改代码重烧，实际结果就是永远不去实测。
 *
 *               为什么主用 V 而不是 S：'?' 的状态应答是以 "S " 开头的
 *               （S x y z ...），同一根串口线往上一混，看日志时分不清
 *               哪行是自己发的、哪行是板子回的。所以正式命令字用 V。
 *               但 S 作为别名保留 —— 万一上位机脚本已经按 S 写了，
 *               不至于突然不认。
 *
 *   ?           查询状态，回一行：
 *               S <x_mm> <y_mm> <z_mm> <底座> <肩> <肘> <腕> <夹爪> <旋转> <busy>
 *               busy = 1 表示还在运动，此时应等 DONE 再发下一条
 *
 * ---- 3.0 新增：示教 / 回放（记的是舵机角，不是坐标）----
 *
 *   T [停留ms]  把当前 6 个舵机角记成一个点，停留时间默认 500ms。
 *               回 "OK <总点数>"。运动中/回放中拒绝（ERR:BUSY）——
 *               运动中记下来的是插值中间姿态，回放会差一点。
 *   A <a1>..<a6> [停留ms]
 *               追加一个【指定角度】的点（0~180，停留默认 500ms），回
 *               "OK <总点数>"。和 T 的区别只是角度由上位机给，不取当前姿态。
 *               用途：断联/断电后把上位机缓存的点表原样推回来，不必把手臂
 *               摆到每个姿态再按一次记录。回放中拒绝（ERR:BUSY），满表 ERR:FULL。
 *   L           列出全部点，每点一行：
 *               L <序号> <舵机1..6> <停留ms>
 *               末行 "L END <总数>"（点数为 0 时只有这一行）
 *   P [遍数]    开始回放，不带参数 = 无限循环，P 1 = 放一遍。
 *               每进入一个点推 "PLAY <序号>/<总数>"，整轮结束推 "PLAY END"。
 *               回 "OK <总点数>"，没有点则 "ERR:EMPTY"。
 *   X           停止回放（停在当前姿态，不回原位）
 *   C           清空点表（只清 RAM，不擦 Flash；要真删再发一次 W）
 *   D <序号>    删除第几号点（1 基，与 L 打印的序号一致）
 *   W           把点表写进 Flash 最后一页，上电自动载入
 *
 *   为什么回放能绕开可达性问题：记录和回放都在【关节空间】，
 *   中间不做逆解、不做路径校验。代价是回放点只能是示教过的姿态，
 *   不能在回放时用坐标微调。
 *
 * 错误码：
 *   ERR:CMD      无法识别的命令字
 *   ERR:ARG      参数个数不对或不是数字
 *   ERR:RANGE    坐标绝对值超过上限（挡住「把毫米当米发」）
 *   ERR:OUT      目标点超出机械臂工作空间
 *   ERR:PATH     目标点可达，但当前点到目标的直线中途穿出工作空间
 *   ERR:NOTIMPL  指令已识别但功能尚未实现
 *   ERR:LONG     单行超过 PROTO_LINE_MAX，整行丢弃
 *   ERR:BUSY     正在回放或正在运动，该指令此时不接受
 *   ERR:FULL     示教点已满（PLAY_MAX_POINTS）
 *   ERR:EMPTY    点表为空，无可回放内容
 *   ERR:INDEX    点序号越界
 *   ERR:FLASH    Flash 擦写失败，或代码区已占用存储页
 *
 * 用法：
 *   Uart_Init(&huart1);      // 先起传输层
 *   Protocol_Init();
 *   while (1) { Protocol_Poll(); Motion_Tick(); Play_Tick(); ... }
 */
#ifndef __PROTOCOL_H
#define __PROTOCOL_H

#include "main.h"
#include "usart.h"
#include <stdint.h>

/* 一条命令的最大长度（含结尾 '\0'）。
 * 最长合法命令 "M -0.999 -0.999 -0.999" 只有 24 字节，64 留足余量。 */
#define PROTO_LINE_MAX      64

/* 协议挂在哪个串口上。换口只改这一行。 */
#define PROTO_UART          (&huart1)

/* 初始化：清空行缓冲和状态。必须在 Uart_Init() 之后调用。 */
void Protocol_Init(void);

/* 轮询：把缓冲里的字节取干净并逐字节喂给行解析器；
 * 顺便检查「上一条 M 是否已经走完」，走完就推一行 DONE。
 * 非阻塞、可每轮主循环调用，没有数据时开销只有一次 Uart_Read。 */
void Protocol_Poll(void);

/* 向 PROTO_UART 回一行（自动补 \r\n）。
 * 注意：内部用 vsnprintf，不要传 %f——本工程没开浮点 printf 支持，
 *       需要打印坐标请先换成整数毫米。 */
void Protocol_Reply(const char *fmt, ...);

#endif
